                    <PS.Oli>승인되어 등록된 문제는 다른 이용자의 문제 풀이, 모의시험, 복습 및 PDF에 포함될 수 있습니다. 공개 후에도 오류나 권리침해가 확인되면 정정·비공개 또는 삭제될 수 있습니다. 제출 자료의 이용 허락과 탈퇴 후 처리는 제13조 및 제19조에 따릅니다.</PS.Oli>
