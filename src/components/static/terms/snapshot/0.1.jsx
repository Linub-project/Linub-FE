                    <PS.Oli>공개 중단이나 회원 탈퇴가 이루어져도 이미 적법하게 다운로드하거나 인쇄한 학습용 자료의 사본이 자동 회수되는 것은 아닙니다. 이 조항은 개인정보 삭제 등 법령상 권리를 제한하지 않습니다.</PS.Oli>
